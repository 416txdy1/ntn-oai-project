const assert=require('node:assert/strict');
const {assess}=require('./dashboard.js');
const history=Array.from({length:25},(_,i)=>({wall_s:i,cn_db:20,ingress_kbps:350}));
const current={wall_s:30,cn_db:20,ingress_kbps:350,fps:15,frame_gap_ms:30,phase:'steady',channel_fresh:true,ingress_fresh:true,channel_valid:true};
const check=(patch,context={})=>assess(history,{...current,...patch},context);
assert.equal(check({phase:'blend'}).code,'normal','Switching by itself must not explain stalls');
assert.equal(check({cn_db:4}).code,'channel_change','C/N decrease without business deterioration is not a stall');
assert.equal(check({fps:0,frame_gap_ms:1200}).code,'downstream','Healthy UE ingress does not support a channel cause');
assert.equal(check({cn_db:4,ingress_kbps:75,fps:4}).code,'channel_supply');
assert.equal(check({cn_db:4,ingress_kbps:null,fps:0,ingress_fresh:false}).code,'missing_ingress');
assert.equal(check({cn_db:4,ingress_kbps:75,fps:0,channel_fresh:false}).code,'stale');
assert.equal(check({cn_db:4,ingress_kbps:75,fps:0},{paused:true}).code,'player_inactive');
assert.equal(check({cn_db:4,ingress_kbps:75,fps:0},{publisher_alive:false}).code,'publisher_stopped');
assert.equal(assess([],current).code,'baseline');
assert.equal(check({ingress_kbps:75,fps:0}).code,'supply_low');
assert.equal(check({phase:'blend',ingress_kbps:75,fps:0}).code,'switch_supply');
assert.equal(assess([...history,{wall_s:28,code:'channel_supply'}],{...current,fps:0}).code,'recovery_tail');
assert.equal(assess([...history,{wall_s:1,code:'channel_supply'}],{...current,fps:0}).code,'downstream','Expired channel events must not explain all later stalls');
console.log('Dashboard diagnostic guards: 13 passed');
